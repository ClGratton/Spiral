    bool ExpectReject(const std::string& label, std::span<const u8> bytes, const CommonImageLimits& limits,
        std::string_view reason)
    {
        DecodedCommonImage output = Sentinel();
        std::string error = "stale error";
        const bool decoded = DecodeCommonImage(bytes, limits, output, error);
        bool passed = Check(!decoded, label + " is rejected");
        passed &= Check(IsSentinel(output), label + " leaves the output untouched");
        passed &= Check(error.find(reason) != std::string::npos,
            label + " reports '" + std::string(reason) + "' but reported '" + error + "'");
        return passed;
    }

    bool ExpectReject(const std::string& label, std::span<const u8> bytes, std::string_view reason)
    {
        return ExpectReject(label, bytes, CommonImageLimits {}, reason);
    }

